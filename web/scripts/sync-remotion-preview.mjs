/**
 * Sync the browser-safe subset of remotion-worker's sources into
 * web/vendor/remotion-preview/ for the spec editor's in-browser preview.
 *
 * Why a copy: the worker sources use NodeNext-style `.js` import specifiers
 * (required so `node dist/` keeps working after tsc), which Turbopack cannot
 * resolve to `.ts` files (vercel/next.js#82945). Importing the sibling
 * directory directly also pulls a second React copy from
 * remotion-worker/node_modules. Copying the fs-free subset into web/ and
 * rewriting the specifiers sidesteps both problems — the vendored files
 * resolve react/remotion/katex/mathjs from web's own node_modules.
 *
 * Runs automatically via npm prebuild/predev hooks; the output directory is
 * gitignored. Do not edit vendor/ files by hand.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(here, "..", "..", "remotion-worker", "src");
const OUT = path.resolve(here, "..", "vendor", "remotion-preview");

// Pure (fs-free) parser modules + the whole scene/component/layout tree.
const FILES = [
  "parser/types.ts",
  "parser/styleChain.ts",
  "parser/themes.ts",
  "remotion/ConceptVideo.tsx",
];
const DIRS = ["components", "scenes", "layouts"];

const HEADER = `// AUTO-GENERATED by scripts/sync-remotion-preview.mjs — do not edit.
// Source: remotion-worker/src (browser-safe subset for the spec preview).
`;

function collect() {
  const files = [...FILES];
  for (const dir of DIRS) {
    for (const entry of fs.readdirSync(path.join(SRC, dir))) {
      if (/\.(ts|tsx)$/.test(entry)) files.push(`${dir}/${entry}`);
    }
  }
  return files;
}

function transform(text) {
  // NodeNext-style relative specifiers (`./x.js`) → extensionless so
  // Turbopack/webpack + TS `moduleResolution: bundler` resolve the .ts/.tsx.
  let out = text.replace(
    /(from\s+['"])(\.\.?\/[^'"]+)\.js(['"])/g,
    "$1$2$3",
  );
  out = out.replace(
    /(import\s*\(\s*['"])(\.\.?\/[^'"]+)\.js(['"]\s*\))/g,
    "$1$2$3",
  );
  // Global CSS (katex) is imported by the app page instead — global CSS
  // imports are only allowed from the app/ directory or node_modules.
  out = out.replace(/^import\s+['"][^'"]+\.css['"];?\s*\n/gm, "");
  return HEADER + out;
}

function main() {
  fs.rmSync(OUT, { recursive: true, force: true });
  let count = 0;
  for (const rel of collect()) {
    const src = path.join(SRC, rel);
    const dest = path.join(OUT, rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, transform(fs.readFileSync(src, "utf8")));
    count += 1;
  }
  console.log(`[sync-remotion-preview] synced ${count} files → vendor/remotion-preview/`);
}

main();
